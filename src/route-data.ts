function getRouteCoords(): [number, number][] {
  const coords: [number, number][] = []
  for (let i = 0; i < routePoints.length; i++) {
    if (i < osrmSegments.length && osrmSegments[i].length > 0) {
      const seg = osrmSegments[i]
      if (coords.length === 0) {
        coords.push(...seg)
      } else {
        coords.push(...seg.slice(1))
      }
    } else {
      const p = routePoints[i]
      if (coords.length === 0 || coords[coords.length - 1][0] !== p.lon || coords[coords.length - 1][1] !== p.lat) {
        coords.push([p.lon, p.lat])
      }
    }
  }
  return coords
}

export function getRouteArrows(): Feature[] {
  const coords = getRouteCoords()
  if (coords.length < 2) return []

  const arrowSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><polygon points="12,0 0,24 12,18 24,24" fill="#2196F3"/></svg>`
  const src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(arrowSvg)
  const features: Feature[] = []
  const step = Math.max(1, Math.floor(coords.length / 50))
  const totalDist = getTotalDistance(coords)

  let accumulated = 0
  for (let i = 1; i < coords.length; i++) {
    const dx = coords[i][0] - coords[i - 1][0]
    const dy = coords[i][1] - coords[i - 1][1]
    accumulated += Math.sqrt(dx * dx + dy * dy)
    if (i % step === 0 && accumulated > totalDist * 0.01) {
      const angle = Math.atan2(dx, dy)
      const feat = new Feature(new Point(fromLonLat(coords[i])))
      feat.setStyle(
        new Style({
          image: new Icon({
            src,
            scale: 0.8,
            rotation: angle,
            opacity: 0.7,
          }),
        })
      )
      features.push(feat)
    }
  }
  return features
}

function getTotalDistance(coords: [number, number][]): number {
  let total = 0
  for (let i = 1; i < coords.length; i++) {
    const dx = coords[i][0] - coords[i - 1][0]
    const dy = coords[i][1] - coords[i - 1][1]
    total += Math.sqrt(dx * dx + dy * dy)
  }
  return total
}

export function getRouteLine(): Feature | null {
  const coords = getRouteCoords().map(c => fromLonLat(c))
  if (coords.length < 2) return null
  const line = new Feature(new LineString(coords))
  line.setStyle([
    new Style({
      stroke: new Stroke({
        color: 'rgba(33, 150, 243, 0.25)',
        width: 14,
      }),
    }),
    new Style({
      stroke: new Stroke({
        color: '#2196F3',
        width: 6,
      }),
    }),
  ])
  return line
}

export function getRoutePoints(): Feature[] {
  return routePoints.map((p, i) => {
    const feat = new Feature(new Point(fromLonLat([p.lon, p.lat])))
    const color = i === 0 ? '#52c41a' : i === routePoints.length - 1 ? '#d4380d' : '#fa8c16'

    feat.setStyle(
      new Style({
        image: new Circle({
          radius: 11,
          fill: new Fill({ color }),
          stroke: new Stroke({ color: '#fff', width: 3 }),
        }),
        text: new Text({
          text: i === 0 || i === routePoints.length - 1 ? '' : `${i}`,
          font: 'bold 10px sans-serif',
          fill: new Fill({ color: '#fff' }),
          stroke: new Stroke({ color: 'rgba(0,0,0,0.3)', width: 2 }),
          textAlign: 'center',
          textBaseline: 'middle',
        }),
      })
    )
    feat.set('name', p.name)
    feat.set('id', p.id)
    return feat
  })
}
